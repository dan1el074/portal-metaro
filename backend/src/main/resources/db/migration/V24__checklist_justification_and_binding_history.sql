ALTER TABLE tb_checklist_record DROP CONSTRAINT ck_checklist_record_status;
ALTER TABLE tb_checklist_record ADD CONSTRAINT ck_checklist_record_status
    CHECK (status IN ('DRAFT','IN_PROGRESS','PENDING','FINISHED','JUSTIFIED','CANCELLED'));

-- Convert only manually skipped records from flows that were never cancelled.
-- Original answers and media remain stored for the revision created on reopening.
UPDATE tb_checklist_record SET status = 'JUSTIFIED'
WHERE status = 'CANCELLED'
  AND EXISTS (SELECT 1 FROM tb_checklist_flow f WHERE f.id = tb_checklist_record.flow_id AND f.cancelled = FALSE)
  AND EXISTS (SELECT 1 FROM tb_checklist_audit a WHERE a.record_id = tb_checklist_record.id AND a.action = 'CHECKLIST_SKIPPED');

CREATE TABLE tb_checklist_step_binding_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES tb_stepflow_order(id) ON DELETE CASCADE,
    flow_id BIGINT NOT NULL REFERENCES tb_checklist_flow(id) ON DELETE CASCADE,
    order_number VARCHAR(80) NOT NULL,
    linked_at TIMESTAMP WITHOUT TIME ZONE,
    unlinked_at TIMESTAMP WITHOUT TIME ZONE
);
CREATE INDEX idx_checklist_binding_history_flow ON tb_checklist_step_binding_history(flow_id);

INSERT INTO tb_checklist_step_binding_history (order_id, flow_id, order_number, linked_at)
SELECT b.order_id, b.flow_id,
    CASE WHEN o.occurrence > 1 THEN CONCAT(CAST(o.number AS VARCHAR), '-', CAST(o.occurrence AS VARCHAR)) ELSE CAST(o.number AS VARCHAR) END,
    b.created_at
FROM tb_checklist_step_binding b JOIN tb_stepflow_order o ON o.id = b.order_id;

-- Recover old relocations only when the serial identifies exactly one checklist flow.
-- The original link date was not stored; it remains NULL for recovered history.
INSERT INTO tb_checklist_step_binding_history (order_id, flow_id, order_number, unlinked_at)
SELECT o.id, f.id,
    CASE WHEN o.occurrence > 1 THEN CONCAT(CAST(o.number AS VARCHAR), '-', CAST(o.occurrence AS VARCHAR)) ELSE CAST(o.number AS VARCHAR) END,
    MIN(m.created_at)
FROM tb_checklist_flow f
JOIN tb_stepflow_step_message m ON LEFT(m.message, LENGTH(CONCAT('O número de série ', f.serial_number, ' foi realocado para '))) = CONCAT('O número de série ', f.serial_number, ' foi realocado para ')
    AND RIGHT(m.message, LENGTH(' pelo setor PCP.')) = ' pelo setor PCP.'
JOIN tb_stepflow_order_step s ON s.id = m.step_id
JOIN tb_stepflow_order o ON o.id = s.order_id
WHERE f.serial_number IS NOT NULL AND f.serial_number <> ''
  AND (SELECT COUNT(*) FROM tb_checklist_flow other_flow WHERE other_flow.serial_number = f.serial_number) = 1
  AND NOT EXISTS (SELECT 1 FROM tb_checklist_step_binding_history h WHERE h.flow_id = f.id AND h.order_id = o.id)
GROUP BY o.id, o.number, o.occurrence, f.id;
