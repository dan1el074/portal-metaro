CREATE TABLE tb_serial_plate (
    serial BIGINT PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    manufacturing_order VARCHAR(80) NOT NULL,
    order_number VARCHAR(15) NOT NULL DEFAULT '',
    order_item VARCHAR(64) NOT NULL DEFAULT '',
    ready_stock BOOLEAN NOT NULL DEFAULT FALSE,
    client VARCHAR(500) NOT NULL DEFAULT '',
    description VARCHAR(1000) NOT NULL DEFAULT '',
    capacity NUMERIC(18,6),
    voltage VARCHAR(120) NOT NULL DEFAULT '',
    weight NUMERIC(18,6),
    provider VARCHAR(255) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL DEFAULT 'Criado',
    notes TEXT NOT NULL DEFAULT '',
    manufactured VARCHAR(7) NOT NULL,
    updated TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT ck_serial_plate_positive CHECK (serial > 0),
    CONSTRAINT ck_serial_plate_capacity CHECK (capacity IS NULL OR capacity > 0),
    CONSTRAINT ck_serial_plate_weight CHECK (weight IS NULL OR weight > 0),
    CONSTRAINT ck_serial_plate_status CHECK (status IN ('Criado','Programado','Terceiro','Recebido','Finalizado')),
    CONSTRAINT ck_serial_plate_pe CHECK (NOT ready_stock OR (order_number = '' AND client = '' AND order_item = ''))
);
CREATE INDEX idx_serial_plate_status_serial ON tb_serial_plate(status, serial);
CREATE TABLE tb_serial_plate_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial BIGINT REFERENCES tb_serial_plate(serial),
    user_id BIGINT NOT NULL REFERENCES tb_user(id),
    author VARCHAR(255) NOT NULL,
    at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    changes_json TEXT NOT NULL
);
CREATE INDEX idx_serial_plate_log_serial ON tb_serial_plate_log(serial, at, id);

