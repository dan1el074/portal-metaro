package br.com.metaro.portal.modules.quality.checklist;

import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.datasource.init.ScriptUtils;

import java.sql.DriverManager;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

class ChecklistModuleMigrationTests {
    @Test
    void linksOnlyActiveLegacyMatchesAndEnforcesExclusiveReservation() throws Exception {
        try (var connection = DriverManager.getConnection("jdbc:h2:mem:serial-link-" + UUID.randomUUID());
             var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE tb_serial_plate (serial BIGINT PRIMARY KEY)");
            statement.execute("CREATE TABLE tb_checklist_flow (id BIGINT PRIMARY KEY, normalized_serial VARCHAR(120), cancelled BOOLEAN NOT NULL)");
            statement.execute("INSERT INTO tb_serial_plate VALUES (18918), (18919)");
            statement.execute("INSERT INTO tb_checklist_flow VALUES (1, '18918', FALSE), (2, NULL, TRUE), (3, 'LEGACY-A', FALSE)");
            ScriptUtils.executeSqlScript(connection, new ClassPathResource("db/migration/V22__link_checklist_serial_plates.sql"));
            try (var result = statement.executeQuery("SELECT serial_plate_id, ready_stock, serial_waived, erp_data_json FROM tb_checklist_flow ORDER BY id")) {
                result.next(); assertThat(result.getLong(1)).isEqualTo(18918L);
                assertThat(result.getBoolean(2)).isFalse(); assertThat(result.getBoolean(3)).isFalse(); assertThat(result.getString(4)).isEqualTo("{}");
                result.next(); assertThat(result.getObject(1)).isNull();
                result.next(); assertThat(result.getObject(1)).isNull();
            }
            org.assertj.core.api.Assertions.assertThatThrownBy(() -> statement.execute("INSERT INTO tb_checklist_flow (id, cancelled, serial_plate_id) VALUES (4, FALSE, 18918)"))
                    .isInstanceOf(java.sql.SQLException.class);
            statement.execute("UPDATE tb_checklist_flow SET cancelled = TRUE, normalized_serial = NULL, serial_plate_id = NULL WHERE id = 1");
            statement.execute("INSERT INTO tb_checklist_flow (id, cancelled, serial_plate_id) VALUES (4, FALSE, 18918)");
        }
    }

    @Test
    void createsChecklistSchemaAndSeedsApprovedCatalogs() throws Exception {
        try (var connection = DriverManager.getConnection("jdbc:h2:mem:checklist-module-" + UUID.randomUUID());
            var statement = connection.createStatement()) {
            statement.execute("""
                CREATE TABLE tb_role (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    authority VARCHAR(255), title VARCHAR(255), title_url VARCHAR(255),
                    parent VARCHAR(255), parent_url VARCHAR(255),
                    father_id BIGINT REFERENCES tb_role(id), activated BOOLEAN
                )
                """);
            statement.execute("CREATE TABLE tb_user (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
            statement.execute("CREATE TABLE tb_picture (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
            statement.execute("CREATE TABLE tb_video (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
            statement.execute("CREATE TABLE tb_stepflow_order (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
            statement.execute("CREATE TABLE tb_stepflow_order_step (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
            statement.execute("INSERT INTO tb_stepflow_order DEFAULT VALUES");
            ScriptUtils.executeSqlScript(connection, new ClassPathResource("db/migration/V17__create_checklist_module.sql"));
            ScriptUtils.executeSqlScript(connection, new ClassPathResource("db/migration/V19__add_optional_checklist_predecessor.sql"));
            statement.execute("INSERT INTO tb_checklist_category (name, integration, document_title) VALUES ('Produção', 'PRODUCTION', 'Produção')");
            ScriptUtils.executeSqlScript(connection, new ClassPathResource("db/migration/V21__add_checklist_category_media.sql"));

            statement.execute("INSERT INTO tb_stepflow_order DEFAULT VALUES");

            statement.execute("INSERT INTO tb_checklist_category (name, integration, document_title) VALUES ('Auditoria 5S', 'FIVE_S', 'Auditoria 5S')");

            try (var result = statement.executeQuery("SELECT COUNT(*) FROM tb_checklist_catalog_entry WHERE type = 'ITEM'")) {
                result.next();
                assertThat(result.getInt(1)).isEqualTo(89);
            }
            try (var result = statement.executeQuery("SELECT COUNT(*) FROM tb_checklist_catalog_entry WHERE type = 'DEFECT'")) {
                result.next();
                assertThat(result.getInt(1)).isEqualTo(52);
            }
            try (var result = statement.executeQuery("SELECT COUNT(*) FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME LIKE 'TB_CHECKLIST_%'")) {
                result.next();
                assertThat(result.getInt(1)).isEqualTo(13);
            }
            try (var result = statement.executeQuery("SELECT COUNT(*) FROM tb_role WHERE authority LIKE 'ROLE_CHECKLIST%' AND activated = TRUE")) {
                result.next();
                assertThat(result.getInt(1)).isEqualTo(4);
            }
            try (var result = statement.executeQuery("SELECT checklist_integration FROM tb_stepflow_order ORDER BY id")) {
                result.next();
                assertThat(result.getBoolean(1)).isFalse();
                result.next();
                assertThat(result.getBoolean(1)).isTrue();
            }
            try (var result = statement.executeQuery("SELECT column_default FROM information_schema.columns WHERE table_name = 'TB_STEPFLOW_ORDER_STEP' AND column_name = 'CHECKLIST_PENDING'")) {
                result.next();
                assertThat(result.getString(1)).isEqualTo("FALSE");
            }
            try (var result = statement.executeQuery("SELECT column_default FROM information_schema.columns WHERE table_name = 'TB_CHECKLIST_TEMPLATE' AND column_name = 'OPTIONAL_PREDECESSOR'")) {
                result.next();
                assertThat(result.getString(1)).isEqualTo("FALSE");
            }
            try (var result = statement.executeQuery("SELECT column_default FROM information_schema.columns WHERE table_name = 'TB_CHECKLIST_CATEGORY' AND column_name = 'MEDIA_ENABLED'")) {
                result.next();
                assertThat(result.getString(1)).isEqualTo("FALSE");
            }
            try (var result = statement.executeQuery("SELECT media_enabled FROM tb_checklist_category WHERE integration = 'PRODUCTION'")) {
                result.next();
                assertThat(result.getBoolean(1)).isTrue();
            }
            try (var result = statement.executeQuery("SELECT parent_url, title_url FROM tb_role WHERE authority = 'ROLE_CHECKLIST'")) {
                result.next();
                assertThat(result.getString(1) + result.getString(2)).isEqualTo("/qualidade/checklist");
            }
            try (var result = statement.executeQuery("""
                    SELECT COUNT(*) FROM tb_role child JOIN tb_role parent ON child.father_id = parent.id
                    WHERE parent.authority = 'ROLE_CHECKLIST'
                    AND child.authority IN ('ROLE_CHECKLIST_ADMIN', 'ROLE_CHECKLIST_OPERATOR', 'ROLE_CHECKLIST_CONSULTATION')
                    """)) {
                result.next();
                assertThat(result.getInt(1)).isEqualTo(3);
            }
        }
    }
}
