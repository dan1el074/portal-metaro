package br.com.metaro.portal.modules.pcp.serialplates;

import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.datasource.init.ScriptUtils;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.UUID;
import static org.assertj.core.api.Assertions.*;

class SerialPlateMigrationTests {
    @Test
    void expandsStatusConstraintWithoutReclassifyingExistingPlates() throws Exception {
        try (var connection = DriverManager.getConnection("jdbc:h2:mem:plate-status-" + UUID.randomUUID());
             var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE tb_user (id BIGINT PRIMARY KEY)");
            statement.execute("CREATE TABLE tb_param (name VARCHAR(255), content TEXT)");
            statement.execute("CREATE TABLE tb_role (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, authority VARCHAR(255), title VARCHAR(255), title_url VARCHAR(255), parent VARCHAR(255), parent_url VARCHAR(255), father_id BIGINT, activated BOOLEAN)");
            ScriptUtils.executeSqlScript(connection, new ClassPathResource("db/migration/V20__create_serial_plates.sql"));
            statement.execute("INSERT INTO tb_serial_plate (serial, manufacturing_order, status, manufactured, updated) VALUES (18918, '8301', 'Terceiro', '2026-10', CURRENT_TIMESTAMP)");
            ScriptUtils.executeSqlScript(connection, new ClassPathResource("db/migration/V23__add_returned_serial_plate_status.sql"));
            try (var result = statement.executeQuery("SELECT status FROM tb_serial_plate WHERE serial = 18918")) {
                result.next(); assertThat(result.getString(1)).isEqualTo("Terceiro");
            }
            statement.execute("UPDATE tb_serial_plate SET status = 'Devolvido' WHERE serial = 18918");
            assertThatThrownBy(() -> statement.execute("UPDATE tb_serial_plate SET status = 'Inexistente' WHERE serial = 18918"))
                    .isInstanceOf(SQLException.class);
        }
    }
}
